CREATE TABLE `quotes` (
  `id` int NOT NULL AUTO_INCREMENT,
  `handymanId` int NOT NULL,
  `referralJobId` int,
  `sourceType` enum('saskhandy_referral','handyman_customer') NOT NULL,
  `homeownerName` varchar(255) NOT NULL,
  `homeownerEmail` varchar(320),
  `homeownerPhone` varchar(30),
  `address` varchar(500),
  `title` varchar(255) NOT NULL,
  `scope` text NOT NULL,
  `lineItems` text,
  `customerNote` text,
  `terms` text,
  `subtotal` decimal(10,2) NOT NULL,
  `taxRate` decimal(5,2),
  `taxAmount` decimal(10,2) NOT NULL DEFAULT '0.00',
  `totalAmount` decimal(10,2) NOT NULL,
  `platformFeeRate` decimal(5,2) NOT NULL,
  `platformFeeAmount` decimal(10,2) NOT NULL,
  `status` enum('draft','sent','viewed','approved','declined','expired','payment_pending','paid','completed','cancelled','payment_failed') NOT NULL DEFAULT 'draft',
  `publicToken` varchar(128) NOT NULL,
  `stripePaymentIntentId` varchar(255),
  `expiresAt` timestamp NULL,
  `sentAt` timestamp NULL,
  `viewedAt` timestamp NULL,
  `approvedAt` timestamp NULL,
  `declinedAt` timestamp NULL,
  `paidAt` timestamp NULL,
  `completedAt` timestamp NULL,
  `createdAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT `quotes_id` PRIMARY KEY (`id`),
  CONSTRAINT `quotes_publicToken_unique` UNIQUE (`publicToken`)
);